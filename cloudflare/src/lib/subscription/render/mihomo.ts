import { stringify as stringifyYaml } from "yaml";
import type { ProxyNode, RoutingTemplateConfig } from "../../../types";
import { defaultProxyGroups, renderTemplateProxyGroups, withRulesetCdn } from "../templates";
import { stripUndefined } from "../utils";

export function renderMihomoYaml(proxies: ProxyNode[], requestUrl: URL, template?: RoutingTemplateConfig, rulesetCdn?: unknown, sourcePath?: string) {
  const config = withRulesetCdn(template, rulesetCdn) || {};
  const mixedPort = config.mixedPort ?? config["mixed-port"] ?? 7890;
  const allowLan = config.allowLan ?? config["allow-lan"] ?? false;
  const logLevel = config.logLevel || config["log-level"] || "info";
  const proxyGroups = config.proxyGroups || config["proxy-groups"] || defaultProxyGroups();
  const ruleProviders = config.ruleProviders || config["rule-providers"];
  const renderedGroups = renderTemplateProxyGroups(proxies.map((proxy) => proxy.name), proxyGroups);
  const fallbackPolicy = renderedGroups[0]?.name || "DIRECT";
  const hasRuleProviders = Boolean(ruleProviders && Object.keys(ruleProviders).length > 0);
  const document = {
    "mixed-port": mixedPort,
    "allow-lan": allowLan,
    mode: config.mode || "rule",
    "log-level": logLevel,
    ...(config.dns ? { dns: config.dns } : {}),
    ...(config.sniffer ? { sniffer: config.sniffer } : {}),
    proxies: proxies.map(stripUndefined),
    "proxy-groups": renderedGroups,
    ...(hasRuleProviders ? { "rule-providers": ruleProviders } : {}),
    rules: config.rules && config.rules.length > 0 ? config.rules : [`MATCH,${fallbackPolicy}`],
  };

  return [`# Generated by Sub-Store Cloudflare`, `# Source: ${sourcePath || requestUrl.pathname}`, stringifyYaml(document)].join("\n");
}
