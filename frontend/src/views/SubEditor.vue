<template>
  <div v-if="isDis">
  <div class="page-wrapper" @click="handleEditGlobalClick">
    <!-- Single scroll page: display + content + actions (no section tabs, no top icon) -->
    <div class="form-block-wrapper">
      <AppForm class="form" :model-value="form" ref="ruleForm">
        <div class="editor-paper">
          <EditorBasicGroup
            :show-group-titles="showEditorGroupTitles"
            :is-edit-mode="isEditMode"
            :config-name="configName"
            :validate-field="customerBlurValidate"
          />
          <EditorSourceGroup
            v-if="editType === 'subs'"
            :show-group-titles="showEditorGroupTitles"
            :validate-field="customerBlurValidate"
            @fullscreen="isDis = false"
          />
          <EditorCollectionGroup
            v-else-if="editType === 'collections'"
            :show-group-titles="showEditorGroupTitles"
            :is-init="isInit"
          />
        </div>
      </AppForm>
    </div>

    <!-- 节点操作 — same page, continuous scroll -->
    <div class="editor-tab-content editor-actions-content">
      <CommonBlock
        v-if="appearanceSetting.editorCommonDisplayMode !== 'hidden'"
        :default-folded="appearanceSetting.editorCommonDisplayMode === 'collapsed'"
      />
      <ActionBlock
        ref="actionBlockRef"
        :checked="actionsChecked"
        :list="actionsList"
        @updateCustomNameModeFlag="updateCustomNameModeFlag"
        @addAction="addAction"
        @deleteAction="deleteAction"
        @toggleAction="toggleAction"
      />
    </div>
  </div>

  <div class="bottom-btn-wrapper">
    <!-- Single primary action (Save). Compare is secondary, not competing chrome. -->
    <button
      type="button"
      class="compare-link"
      :title="$t('editorPage.subConfig.btn.compare')"
      :disabled="isget"
      @click="compare"
    >
      <font-awesome-icon icon="fa-solid fa-eye" />
      <span>{{ $t("editorPage.subConfig.btn.compare") }}</span>
    </button>
    <AppButton
      @click="submit"
      class="submit-btn btn"
      type="primary"
      shape="square"
      :title="$t('editorPage.subConfig.btn.saveShortcut')"
      :loading="isget"
    >
      <font-awesome-icon icon="fa-solid fa-floppy-disk" />
      {{ $t("editorPage.subConfig.btn.save") }}
    </AppButton>
  </div>
</div>
<div v-else style="width: 100%;max-height: 95dvh;">
    <button class="cimg-button" @click="isDis = true">
      <font-awesome-icon icon="fa-solid fa-minimize" />
      {{ $t(`editorPage.subConfig.basic.url.tips.fullScreenEditCancel`) }}
    </button>
    <CodeEditor />
  </div>
  <CompareTable
    v-if="compareTableIsVisible"
    :name="configName"
    :compareData="compareData"
    :showRefresh="true"
    @closeCompare="closeCompare"
    @refresh="refreshCompare"
  />
</template>

<script lang="ts" setup>
import { storeToRefs } from "pinia";
import {
  computed,
  defineAsyncComponent,
  nextTick,
  onBeforeUnmount,
  onMounted,
  provide,
  reactive,
  ref,
  toRaw,
} from "vue";
import { useI18n } from "vue-i18n";
import { useRoute, useRouter } from "vue-router";

import { useCloudflareApi } from "@/api/app";
import { useCompareOverlay } from "@/hooks/useCompareOverlay";
import { usePopupRoute } from "@/hooks/usePopupRoute";
import { useUnsavedChanges } from "@/hooks/useUnsavedChanges";
import { useAppNotifyStore } from "@/store/appNotify";
import { useSettingsStore } from "@/store/settings";
import { useSubsStore } from "@/store/subs";
import { dialogState, showDialog } from "@/utils/dialog";
import { initStores } from "@/utils/initApp";
import { dismissNotify, notifyLoading } from "@/utils/notify";
import { ensureSubscriptionIcon, isAutoGeneratedIcon } from "@/utils/subscriptionIcon";
import { normalizeTagList } from "@/utils/tagList";
import ActionBlock from "@/views/editor/ActionBlock.vue";
import CommonBlock from "@/views/editor/CommonBlock.vue";
import CodeEditor from "@/views/editor/components/CodeEditor.vue";
import EditorBasicGroup from "@/views/editor/EditorBasicGroup.vue";
import EditorCollectionGroup from "@/views/editor/EditorCollectionGroup.vue";
import EditorSourceGroup from "@/views/editor/EditorSourceGroup.vue";
import { useEditorActions } from "@/views/editor/composables/useEditorActions";
import { useEditorFormModel } from "@/views/editor/composables/useEditorFormModel";
import {
  LOCAL_CONTENT_PREVIEW_KEY,
  useLocalContentPreview,
} from "@/views/editor/composables/useLocalContentPreview";

/* Compare is a full-screen overlay; keep its code out of the editor chunk. */
const CompareTable = defineAsyncComponent(() => import("@/views/CompareTable.vue"));

const isDis = ref(true);
const { t } = useI18n();
const route = useRoute();
const router = useRouter();
const cloudflareApi = useCloudflareApi();
const editType = route.params.editType as string;
const configName = route.params.id as string;
const subsStore = useSubsStore();
const { showNotify } = useAppNotifyStore();

const settingsStore = useSettingsStore();
const { appearanceSetting } = storeToRefs(settingsStore);

const padding = "env(safe-area-inset-bottom)";

const form = reactive<any>({
  name: "",
  displayName: "",
  form: "",
  remark: "",
  ignoreFailedRemoteSub: false,
  passThroughUA: false,
  icon: "",
  // Public SVG avatars stay colored (no desaturate filter)
  isIconColor: true,
  process: [],
  /* Saved back as-is: a disabled record must not come back to life on edit. */
  enabled: true,
});
provide("form", form);

const {
  actionsChecked,
  actionsList,
  actionBlockRef,
  addAction,
  deleteAction,
  toggleAction,
  loadActions,
  updateCustomNameModeFlag,
  handleEditGlobalClick,
  toProcess,
} = useEditorActions(form);

const { isInit, isEditMode } = useEditorFormModel({
  form,
  editType,
  configName,
  loadActions,
  onLoaded: () => markClean(),
});

const { markClean } = useUnsavedChanges({
  sources: () => [form, actionsChecked, actionsList],
  isReady: isInit,
});

const localPreview = useLocalContentPreview({ form, toProcess });
provide(LOCAL_CONTENT_PREVIEW_KEY, localPreview);

const {
  compareTableIsVisible,
  compareData,
  openComparePanel,
  closeCompare,
} = useCompareOverlay();

const isget = ref(false);
const ruleForm = ref<any>(null);

/**
 * There are no section tabs any more, but the form is long enough that the
 * offending field is usually off-screen: bring it into view and focus it so
 * "去修改" lands on something.
 */
const revealField = (prop: string) => {
  const item = document.querySelector<HTMLElement>(`.app-form-item[data-prop="${prop}"]`);
  if (!item) return;
  item.scrollIntoView({ block: "center", behavior: "smooth" });
  item.querySelector<HTMLElement>("input, textarea, select")?.focus({ preventScroll: true });
};

let pendingValidationProp: string | null = null;

const focusValidationErrorTab = (errors?: { prop?: string }[] | { prop?: string }) => {
  const prop = Array.isArray(errors) ? errors[0]?.prop : errors?.prop;
  if (!prop) return;
  pendingValidationProp = prop;
  nextTick(() => revealField(prop));
};

/** The dialog takes focus, so land on the field once it closes. */
const focusPendingValidationField = () => {
  const prop = pendingValidationProp;
  pendingValidationProp = null;
  if (prop) nextTick(() => revealField(prop));
};

/** 编辑页分组: always shows the section titles, edit-only hides them while
 *  creating, disabled never shows them. */
const showEditorGroupTitles = computed(() => {
  const mode = appearanceSetting.value.editorGroupingMode || "always";
  if (mode === "disabled") return false;
  if (mode === "edit-only") return isEditMode.value;
  return true;
});

const fetchCompareData = async () => {
  notifyLoading(t("editorPage.subConfig.basic.content.validation.compareLoading"), "compare");
  try {
    const data: any = JSON.parse(JSON.stringify(toRaw(form)));
    data.process = toProcess(data.process);
    if (data.ignoreFailedRemoteSub === "disabled") {
      data.ignoreFailedRemoteSub = false;
    }
    delete data.firstSubFlow;
    delete data.proxy;
    delete data.mergeSources;
    data.tag = [...new Set(normalizeTagList(data.tag))];
    actionsChecked.forEach((item) => {
      if (!item[1]) {
        const index = data.process.findIndex((i) => i.id === item[0]);
        if (index > -1) {
          data.process.splice(index, 1);
        }
      }
    });
    const type = editType === "collections" ? "collection" : "sub";
    const res = await cloudflareApi.previewItem(type, data);
    if (res?.data?.status === "success") {
      compareData.value = res.data.data;
      return true;
    }
  } catch (e) {
    console.error(e);
  } finally {
    dismissNotify("compare");
  }
  /* Keep whatever was on screen: the interceptor already said why it failed,
     and an empty table would read as "every node was filtered out". */
  return false;
};

const compare = () => {
  ruleForm.value.validate().then(async ({ valid, errors }: any) => {
    if (!valid) {
      focusValidationErrorTab(errors);
      showDialog({
        title: t(`editorPage.subConfig.pop.errorTitle`),
        content: errors[0].message,
        noCancelBtn: true,
        okText: t(`editorPage.subConfig.pop.errorBtn`),
        closeOnClickOverlay: true,
        onOk: focusPendingValidationField,
      });
      return;
    }
    if (!(await fetchCompareData())) return;
    openComparePanel();
  });
};

const refreshCompare = async () => {
  await fetchCompareData();
};

const submit = () => {
  if (isget.value) {
    showNotify({
      type: "success",
      title: t("editorPage.subConfig.basic.content.validation.submitBusy"),
    });
    return;
  }
  isget.value = true;
  ruleForm.value.validate().then(async ({ valid, errors }: any) => {
    // 如果验证失败
    if (!valid) {
      focusValidationErrorTab(errors);
      showDialog({
        title: t(`editorPage.subConfig.pop.errorTitle`),
        content: errors[0].message,
        noCancelBtn: true,
        okText: t(`editorPage.subConfig.pop.errorBtn`),
        closeOnClickOverlay: true,
        onOk: focusPendingValidationField,
      });
      return;
    }
    notifyLoading(t("editorPage.subConfig.basic.content.validation.submitLoading"), "submits");
    // 如果验证成功，开始保存/修改
    const data: any = JSON.parse(JSON.stringify(toRaw(form)));
    // Auto icon from public library — no user upload
    const iconSeed = String(data.name || data.displayName || "subscription").trim();
    data.icon = ensureSubscriptionIcon(
      data.icon,
      iconSeed,
      editType === "collections" ? "collection" : "sub",
      !isEditMode.value || isAutoGeneratedIcon(data.icon),
    );
    data.isIconColor = true;
    if (editType === "subs" && data.source === "local") {
      const isValidLocalContent = await localPreview.validate(localPreview.content.value, { notify: true });
      if (!isValidLocalContent) {
        focusValidationErrorTab([{ prop: "content" }]);
        return;
      }
      data.content = localPreview.content.value;
    }
    delete data.proxy;
    delete data.mergeSources;
    data.tag = [...new Set(normalizeTagList(data.tag))];
    data["display-name"] = data.displayName;
    data.process = toProcess(data.process);
    if (data.ignoreFailedRemoteSub === "disabled"){
      data.ignoreFailedRemoteSub = false;
    }
    delete data.firstSubFlow;

    let res = null;

    if (configName === "UNTITLED") {
      res = await cloudflareApi.createItem(editType, data);
      await subsStore.fetchSubsData();
      if (data.source === "remote") await initStores(false, true, false);
    } else {
      let apiType = "";
      if (editType === "subs") {
        apiType = "sub";
      } else if (editType === "collections") {
        apiType = "collection";
      }
      res = await cloudflareApi.editItem(apiType, configName, data);

      if (configName === data.name) {
        // @ts-ignore
        await subsStore.updateOneData(editType, configName);
      } else {
        await subsStore.fetchSubsData();
      }
    }

    if (res?.data?.status === "success") {
      markClean();
      router.replace("/").then(() => {
        if (res)
          showNotify({
            type: "success",
            title: t(`editorPage.subConfig.pop.succeedMsg`),
          });
      });
    }
  }).catch(() => {
    // The shared axios interceptor already reported the failure. Swallow it
    // here so `finally` can release the save guard and the user can retry.
  }).finally(() => {
    isget.value = false;
    dismissNotify("submits");
  });
};

/** ⌘S / Ctrl+S saves, like every other editor — otherwise the browser's
 *  own "save page" dialog opens mid-edit. */
const onSaveShortcut = (event: KeyboardEvent) => {
  if (!(event.metaKey || event.ctrlKey) || event.key.toLowerCase() !== "s") return;
  /* Always swallow it: the browser's "save page" dialog is never what we want here. */
  event.preventDefault();
  if (dialogState.visible) return;
  submit();
};
/* Every other overlay closes on Escape; the full-screen editor should too.
   A key CodeMirror already handled (its search panel) is left alone. */
const onFullscreenEscape = (event: KeyboardEvent) => {
  if (event.key !== "Escape" || isDis.value || event.defaultPrevented) return;
  isDis.value = true;
};

onMounted(() => {
  window.addEventListener("keydown", onSaveShortcut);
  window.addEventListener("keydown", onFullscreenEscape);
});
onBeforeUnmount(() => {
  window.removeEventListener("keydown", onSaveShortcut);
  window.removeEventListener("keydown", onFullscreenEscape);
});

  // 失去焦点触发验证
  const customerBlurValidate = (prop: string) => {
    ruleForm.value.validate(prop);
  };

  /* 全屏编辑 is a full-screen mode like the compare overlay: Back should leave
     the mode, not the editor. */
  const isFullscreenEditing = computed({
    get: () => !isDis.value,
    set: (value: boolean) => {
      isDis.value = !value;
    },
  });
  usePopupRoute(isFullscreenEditing, { rewindOnClose: true });
</script>

