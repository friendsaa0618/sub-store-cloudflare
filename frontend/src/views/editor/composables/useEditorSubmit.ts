import { onBeforeUnmount, onMounted, ref, toRaw, type Ref } from "vue";
import { useI18n } from "vue-i18n";
import { useRouter } from "vue-router";

import { useCloudflareApi } from "@/api/app";
import { useAppNotifyStore } from "@/store/appNotify";
import { useSubsStore } from "@/store/subs";
import { dialogState } from "@/utils/dialog";
import { initStores } from "@/utils/initApp";
import { dismissNotify, notifyLoading } from "@/utils/notify";
import { ensureSubscriptionIcon, isAutoGeneratedIcon } from "@/utils/subscriptionIcon";
import { normalizeTagList } from "@/utils/tagList";
import type { LocalContentPreview } from "@/views/editor/composables/useLocalContentPreview";

type UseEditorSubmitOptions = {
  form: Record<string, any>;
  editType: string;
  configName: string;
  isEditMode: Ref<boolean>;
  actionsChecked: [string | undefined, boolean][];
  /** Persisted process for the current action rows. */
  toProcess: (process: Process[]) => Process[];
  validateForm: () => Promise<boolean>;
  focusValidationErrorTab: (errors?: { prop?: string }[] | { prop?: string }) => void;
  localPreview: LocalContentPreview;
  markClean: () => void;
};

/**
 * Saving the editor form: build the persisted payload, validate local content,
 * create or update the record, refresh the stores, and leave the page.
 */
export const useEditorSubmit = ({
  form,
  editType,
  configName,
  isEditMode,
  actionsChecked,
  toProcess,
  validateForm,
  focusValidationErrorTab,
  localPreview,
  markClean,
}: UseEditorSubmitOptions) => {
  const { t } = useI18n();
  const router = useRouter();
  const cloudflareApi = useCloudflareApi();
  const subsStore = useSubsStore();
  const { showNotify } = useAppNotifyStore();

  const isSubmitting = ref(false);

  const submit = async () => {
    if (isSubmitting.value) {
      showNotify({
        type: "success",
        title: t("editorPage.subConfig.basic.content.validation.submitBusy"),
      });
      return;
    }
    isSubmitting.value = true;
    try {
      if (!(await validateForm())) return;
      notifyLoading(t("editorPage.subConfig.basic.content.validation.submitLoading"), "submits");

      // 如果验证成功，开始保存/修改
      const data: any = JSON.parse(JSON.stringify(toRaw(form)));
      // Auto icon from public library — no user upload
      const iconSeed = String(data.name || data.displayName || "subscription").trim();
      data.icon = ensureSubscriptionIcon(
        data.icon,
        iconSeed,
        editType === "collections" ? "collection" : "sub",
        !isEditMode.value || isAutoGeneratedIcon(data.icon),
      );
      data.isIconColor = true;
      if (editType === "subs" && data.source === "local") {
        const isValidLocalContent = await localPreview.validate(localPreview.content.value, { notify: true });
        if (!isValidLocalContent) {
          focusValidationErrorTab([{ prop: "content" }]);
          return;
        }
        data.content = localPreview.content.value;
      }
      delete data.proxy;
      delete data.mergeSources;
      data.tag = [...new Set(normalizeTagList(data.tag))];
      data["display-name"] = data.displayName;
      data.process = toProcess(data.process);
      if (data.ignoreFailedRemoteSub === "disabled") {
        data.ignoreFailedRemoteSub = false;
      }
      delete data.firstSubFlow;

      let res = null;

      if (configName === "UNTITLED") {
        res = await cloudflareApi.createItem(editType, data);
        await subsStore.fetchSubsData();
        if (data.source === "remote") await initStores(false, true, false);
      } else {
        let apiType = "";
        if (editType === "subs") {
          apiType = "sub";
        } else if (editType === "collections") {
          apiType = "collection";
        }
        res = await cloudflareApi.editItem(apiType, configName, data);

        if (configName === data.name) {
          // @ts-ignore
          await subsStore.updateOneData(editType, configName);
        } else {
          await subsStore.fetchSubsData();
        }
      }

      if (res?.data?.status === "success") {
        markClean();
        router.replace("/").then(() => {
          if (res)
            showNotify({
              type: "success",
              title: t(`editorPage.subConfig.pop.succeedMsg`),
            });
        });
      }
    } catch {
      // The shared axios interceptor already reported the failure. Swallow it
      // here so `finally` can release the save guard and the user can retry.
    } finally {
      isSubmitting.value = false;
      dismissNotify("submits");
    }
  };

  /** ⌘S / Ctrl+S saves, like every other editor — otherwise the browser's
   *  own "save page" dialog opens mid-edit. */
  const onSaveShortcut = (event: KeyboardEvent) => {
    if (!(event.metaKey || event.ctrlKey) || event.key.toLowerCase() !== "s") return;
    /* Always swallow it: the browser's "save page" dialog is never what we want here. */
    event.preventDefault();
    if (dialogState.visible) return;
    void submit();
  };

  onMounted(() => window.addEventListener("keydown", onSaveShortcut));
  onBeforeUnmount(() => window.removeEventListener("keydown", onSaveShortcut));

  return { isSubmitting, submit };
};
